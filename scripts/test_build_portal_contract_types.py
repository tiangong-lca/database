#!/usr/bin/env python3
"""Two-point input guards must never replace actual schema generation."""
import json
import tempfile
import unittest
from pathlib import Path
from unittest.mock import patch

import build_portal_contract_types as generator


class PortalGenerationTests(unittest.TestCase):
    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory()
        self.addCleanup(self.temporary.cleanup)
        self.root = Path(self.temporary.name)
        schemas = self.root / "contracts/portal"
        outputs = schemas / "generated"
        outputs.mkdir(parents=True)
        (schemas / "sample.schema.json").write_text('{"type":"string"}\n')
        (outputs / "sample.d.ts").write_text("export type Sample = string;\n")
        self.tool = self.root / "generator.py"
        self.tool.write_text("original generator")
        self.addCleanup(patch.stopall)
        patch.multiple(generator, REPO_ROOT=self.root, SCHEMA_DIR=schemas,
                       OUTPUT_DIR=outputs, GENERATOR_PATH=self.tool).start()
        patch.object(generator, "tool_identity", return_value={"node": "test-node", "npx": "test-npx"}).start()
        self.snapshot = self.root / "snapshot.json"
        self.schema = schemas / "sample.schema.json"
        self.output = outputs / "sample.d.ts"

    def test_capture_does_no_generation_and_check_always_renders(self):
        with patch.object(generator, "render_all", return_value={"sample.d.ts": self.output.read_text()}) as render:
            generator.capture_inputs(self.snapshot)
            render.assert_not_called()
            self.assertEqual(generator.check_with_snapshot(self.snapshot), 0)
            render.assert_called_once()

    def test_schema_output_tool_and_inventory_drift_fail(self):
        for changed in [self.schema, self.output, self.tool]:
            with self.subTest(changed=changed.name):
                generator.capture_inputs(self.snapshot)
                original = changed.read_bytes()
                changed.write_bytes(original + b" ")
                with self.assertRaisesRegex(ValueError, "changed"):
                    generator.check_with_snapshot(self.snapshot)
                changed.write_bytes(original)
                self.snapshot.unlink()
        generator.capture_inputs(self.snapshot)
        (generator.SCHEMA_DIR / "new.schema.json").write_text("{}")
        with self.assertRaisesRegex(ValueError, "changed"):
            generator.check_with_snapshot(self.snapshot)

    def test_drift_during_real_generation_is_rejected(self):
        generator.capture_inputs(self.snapshot)
        def changed(_):
            self.schema.write_text("{}")
            return {"sample.d.ts": self.output.read_text()}
        with patch.object(generator, "render_all", side_effect=changed):
            with self.assertRaisesRegex(ValueError, "changed"):
                generator.check_with_snapshot(self.snapshot)

    def test_forged_snapshot_cannot_suppress_actual_generation_failure(self):
        generator.capture_inputs(self.snapshot)
        # Even a matching/fabricated snapshot cannot assert that rendering passed.
        with patch.object(generator, "render_all", return_value={"sample.d.ts": "wrong generated bytes"}) as render:
            self.assertEqual(generator.check_with_snapshot(self.snapshot), 1)
            render.assert_called_once()

    def test_missing_malformed_foreign_and_symlink_snapshots_fail(self):
        with self.assertRaises(FileNotFoundError):
            generator.check_with_snapshot(self.snapshot)
        self.snapshot.write_text('{"passed":true}')
        with self.assertRaisesRegex(ValueError, "changed"):
            generator.check_with_snapshot(self.snapshot)
        self.snapshot.unlink()
        generator.capture_inputs(self.snapshot)
        value = json.loads(self.snapshot.read_text())
        value["root"] = "/foreign/repository"
        self.snapshot.write_text(json.dumps(value))
        with self.assertRaisesRegex(ValueError, "changed"):
            generator.check_with_snapshot(self.snapshot)
        link = self.root / "link.json"
        link.symlink_to(self.snapshot)
        with self.assertRaisesRegex(ValueError, "regular"):
            generator.check_with_snapshot(link)

    def test_capture_refuses_overwrite_and_symlink_inputs(self):
        generator.capture_inputs(self.snapshot)
        with self.assertRaises(FileExistsError):
            generator.capture_inputs(self.snapshot)
        self.schema.unlink()
        self.schema.symlink_to(self.output)
        with self.assertRaisesRegex(ValueError, "regular"):
            generator.capture_inputs(self.root / "second.json")


if __name__ == "__main__":
    unittest.main()
